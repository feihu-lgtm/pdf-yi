// Run: node tools/tests/book-packing.cjs
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname, '../..');
const c = vm.createContext({ console, Headers, Blob, Response, AbortController, setTimeout, clearTimeout, cacheKey: 'test', localStorage: { getItem: () => null }, fetch() {}, addTransLog() {}, toast() {}, setStatus() {} });
c.window = c; c.PDFYI_WORKER = true;
for (const f of ['textutil.js', 'translate.js']) vm.runInContext(fs.readFileSync(path.join(root, 'www/core', f), 'utf8'), c);
(async () => {
  const entries = [{ page: 1, index: 0, text: 'a'.repeat(1800) }, { page: 1, index: 1, text: 'b'.repeat(900) }, { page: 2, index: 0, text: 'c'.repeat(250) }, { page: 2, index: 1, text: 'd'.repeat(6100) }];
  const packed = c.packTranslationEntries(entries);
  assert.equal(packed[0].length, 3, 'packs across page boundary');
  for (const batch of packed) { assert.ok(batch.length <= 24); assert.ok(batch.reduce((n, e) => n + e.text.length, 0) <= 3000); }
  assert.deepEqual(Array.from(packed.flat(), e => `${e.page}:${e.index}`), ['1:0', '1:1', '2:0', '2:1', '2:1', '2:1']);
  assert.equal(packed.flat().filter(e => e.index === 1 && e.page === 2).map(e => e.text).join(''), entries[3].text);
  assert.equal(c.packTranslationEntries(Array.from({ length: 50 }, (_, i) => ({ page: 1, index: i, text: 'x' })))[0].length, 24);
  const deferred = [], persisted = [], pages = [{ page: 1, texts: ['a'.repeat(1800), 'b'.repeat(1800)] }, { page: 2, texts: ['c'.repeat(1800), '中文原段'] }];
  c.translatePage = async (page, texts) => new Promise(resolve => deferred.push({ page, texts, resolve }));
  const translating = c.translateBook(pages, { schedule: async (batches, work) => Promise.all(batches.map(work)), onPage: async (p, result) => persisted.push({ p, result: Array.from(result) }) });
  await Promise.resolve(); assert.equal(deferred.length, 3);
  deferred[1].resolve(['乙']); await new Promise(setImmediate);
  assert.equal(persisted.length, 0, 'partial page is never persisted');
  deferred[2].resolve(['丙']); await new Promise(setImmediate);
  assert.deepEqual(persisted, [{ p: 2, result: ['丙', '中文原段'] }]);
  deferred[0].resolve(['甲']); await translating;
  assert.deepEqual(persisted[1], { p: 1, result: ['甲', '乙'] });
  const retry = vm.createContext({ console, Headers, Blob, Response, AbortController, setTimeout, clearTimeout, cacheKey: 'retry', localStorage: { getItem: () => null }, fetch() {}, addTransLog() {}, toast() {}, setStatus() {} });
  retry.window = retry; retry.PDFYI_WORKER = true;
  for (const f of ['textutil.js', 'translate.js']) vm.runInContext(fs.readFileSync(path.join(root, 'www/core', f), 'utf8'), retry);
  const calls = [];
  retry.apiBatch = async (key, texts) => { calls.push(Array.from(texts)); return calls.length === 1 ? texts.map(() => '__TRANSFAIL__未匹配到译文') : texts.map(t => '译' + t); };
  const result = await retry.translatePage(1, ['one', 'two', 'three', 'four']);
  assert.deepEqual(Array.from(result), ['译one', '译two', '译three', '译four']);
  assert.deepEqual(calls.map(x => x.length), [4, 2, 2]);
  const longCalls = [];
  retry.apiBatch = async (_, texts) => { longCalls.push(Array.from(texts)); return texts.map(() => longCalls.length === 2 ? '__TRANSFAIL__HTTP 503 unavailable' : '分段译文'); };
  const longResult = await retry.translatePage(1, ['z'.repeat(6100)]);
  assert.ok(longCalls.every(texts => texts.reduce((n, t) => n + t.length, 0) <= 3000), 'retries also split oversized paragraphs');
  assert.match(longResult[0], /^__TRANSFAIL__HTTP 503/, 'a failed later fragment never masquerades as a complete paragraph');
  const mergeLogs = [];
  const merge = vm.createContext({ console: { warn() {} }, Headers, Blob, Response, AbortController, setTimeout, clearTimeout, cacheKey: 'merge', localStorage: { getItem: () => null }, fetch: async () => new Response(JSON.stringify({ choices: [{ message: { content: '[[1,3]]' } }] })), addTransLog: (...args) => mergeLogs.push(args), toast() {}, setStatus() {} });
  merge.window = merge; merge.PDFYI_WORKER = true;
  for (const f of ['textutil.js', 'translate.js']) vm.runInContext(fs.readFileSync(path.join(root, 'www/core', f), 'utf8'), merge);
  const fallback = await merge.aiMergeLines(['First source line.', 'Second source line.', 'Third source line.'], 'key');
  assert.deepEqual(Array.from(fallback._idx.flat()), [0, 1, 2], 'merge omissions retain every line via layout fallback');
  assert.ok(mergeLogs.some(args => args[4] === '合并' && args[5] === false));
  assert.deepEqual(Array.from((await merge.aiMergeLines(['Single line.'], 'key'))._idx[0]), [0], 'single-line pages retain their bbox indices');
  console.log('PASS: cross-page packing, strict character/paragraph budgets, order, long-paragraph fragments, out-of-order page mapping, complete-only persistence, Chinese passthrough, misalignment split retry');
})().catch(e => { console.error(e); process.exitCode = 1; });
